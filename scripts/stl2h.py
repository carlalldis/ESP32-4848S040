#!/usr/bin/env python3
"""Convert every STL in src/stl/ into src/models_gen.h for the 3-D viewer.

Runs automatically before each PlatformIO build (extra_scripts = pre:...) and
only rewrites the header when an STL is newer than it. Also runs standalone:
    python scripts/stl2h.py

Per model it emits:
  * welded vertices, centred and scaled so the bounding sphere has radius 1,
    converted from Blender's Z-up to the viewer's Y-up (front = -Y -> +Z)
  * triangles as vertex-index triples (CCW seen from outside)
  * face normals and smooth (area-weighted) vertex normals, int8 x127
  * the edge list for wireframe, minus the diagonals inside flat quads/ngons
Binary and ASCII STL are both accepted.
"""
import math
import os
import re
import struct
import sys

COLORS = [0xF2A33A, 0x7FD36A, 0x9BB4D6, 0xE0607E, 0x5EC8E0, 0xD8C46A]
COPLANAR_DOT = 0.9995  # edges between faces this flat are not drawn


def read_stl(path):
    data = open(path, "rb").read()
    tris = []
    if len(data) >= 84:
        n = struct.unpack_from("<I", data, 80)[0]
        if 84 + 50 * n == len(data):
            for i in range(n):
                v = struct.unpack_from("<12f", data, 84 + 50 * i)
                tris.append((v[3:6], v[6:9], v[9:12]))
            return tris
    txt = data.decode("ascii", "ignore")
    verts = [tuple(map(float, m)) for m in
             re.findall(r"vertex\s+(\S+)\s+(\S+)\s+(\S+)", txt)]
    return [tuple(verts[i:i + 3]) for i in range(0, len(verts) - 2, 3)]


def sub(a, b): return (a[0] - b[0], a[1] - b[1], a[2] - b[2])
def cross(a, b): return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])
def dot(a, b): return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def norm(a):
    l = math.sqrt(dot(a, a))
    return (a[0] / l, a[1] / l, a[2] / l) if l > 1e-20 else (0.0, 0.0, 0.0)


def convert(path):
    raw = read_stl(path)
    # weld + Z-up -> Y-up
    index, verts, tris = {}, [], []
    for t in raw:
        ids = []
        for (x, y, z) in t:
            p = (x, z, -y)
            key = tuple(round(c, 5) for c in p)
            if key not in index:
                index[key] = len(verts)
                verts.append(p)
            ids.append(index[key])
        if len(set(ids)) == 3:
            tris.append(tuple(ids))
    # centre on the bounding box, unit bounding sphere
    lo = [min(v[a] for v in verts) for a in range(3)]
    hi = [max(v[a] for v in verts) for a in range(3)]
    c = [(lo[a] + hi[a]) / 2 for a in range(3)]
    verts = [sub(v, c) for v in verts]
    r = max(math.sqrt(dot(v, v)) for v in verts) or 1.0
    verts = [(v[0] / r, v[1] / r, v[2] / r) for v in verts]

    fn, vn = [], [(0.0, 0.0, 0.0)] * len(verts)
    for (a, b, cc) in tris:
        n = cross(sub(verts[b], verts[a]), sub(verts[cc], verts[a]))  # |n| = 2*area
        fn.append(norm(n))
        for i in (a, b, cc):
            vn[i] = (vn[i][0] + n[0], vn[i][1] + n[1], vn[i][2] + n[2])
    vn = [norm(n) for n in vn]

    edge_faces = {}
    for f, (a, b, cc) in enumerate(tris):
        for e in ((a, b), (b, cc), (cc, a)):
            edge_faces.setdefault((min(e), max(e)), []).append(f)
    edges = [e for e, fs in edge_faces.items()
             if len(fs) != 2 or dot(fn[fs[0]], fn[fs[1]]) < COPLANAR_DOT]
    return verts, tris, fn, vn, sorted(edges)


def i8(v): return max(-127, min(127, int(round(v * 127))))


def pretty(stem):
    s = re.sub(r"(?i)fixed$", "", stem)
    s = re.sub(r"[_\-]+", " ", s)
    s = re.sub(r"(?<=[a-zA-Z])(\d+)$", "", s).strip()
    return s.upper() or stem.upper()


def emit(stl_dir, out_path):
    files = sorted(f for f in os.listdir(stl_dir) if f.lower().endswith(".stl"))
    out = ["/* Generated by scripts/stl2h.py from src/stl/*.stl - do not edit. */",
           "#pragma once", '#include "models.h"', ""]
    entries = []
    for k, f in enumerate(files):
        verts, tris, fn, vn, edges = convert(os.path.join(stl_dir, f))
        sym = re.sub(r"\W", "_", os.path.splitext(f)[0]).lower()
        out.append(f"/* {f}: {len(verts)} vertices, {len(tris)} triangles, {len(edges)} edges */")
        out.append(f"static const float {sym}_v[] = {{")
        out += ["  " + ", ".join(f"{c:.5f}f" for c in v) + "," for v in verts]
        out.append("};")
        out.append(f"static const int8_t {sym}_vn[] = {{")
        out += ["  " + ", ".join(str(i8(c)) for c in n) + "," for n in vn]
        out.append("};")
        out.append(f"static const int8_t {sym}_fn[] = {{")
        out += ["  " + ", ".join(str(i8(c)) for c in n) + "," for n in fn]
        out.append("};")
        out.append(f"static const uint16_t {sym}_t[] = {{")
        for i in range(0, len(tris), 8):
            out.append("  " + " ".join(f"{a},{b},{c}," for (a, b, c) in tris[i:i + 8]))
        out.append("};")
        out.append(f"static const uint16_t {sym}_e[] = {{")
        for i in range(0, len(edges), 12):
            out.append("  " + " ".join(f"{a},{b}," for (a, b) in edges[i:i + 12]))
        out.append("};")
        out.append("")
        name = pretty(os.path.splitext(f)[0])
        entries.append(f'  {{"{name}", {len(verts)}, {len(tris)}, {len(edges)}, {sym}_v, {sym}_vn, '
                       f'{sym}_fn, {sym}_t, {sym}_e, 0x{COLORS[k % len(COLORS)]:06X}}},')
        print(f"[stl2h] {f}: {len(verts)} verts, {len(tris)} tris, {len(edges)} edges")
    out.append("static const Model MODELS[] = {")
    out += entries
    out.append("};")
    out.append(f"static const int N_MODELS = {len(entries)};")
    out.append("")
    with open(out_path, "w", newline="\n") as fh:
        fh.write("\n".join(out))


def run(project_dir):
    stl_dir = os.path.join(project_dir, "src", "stl")
    out_path = os.path.join(project_dir, "src", "models_gen.h")
    srcs = [os.path.join(stl_dir, f) for f in os.listdir(stl_dir) if f.lower().endswith(".stl")]
    newest = max([os.path.getmtime(p) for p in srcs + [stl_dir, os.path.abspath(__file__)]])
    if os.path.exists(out_path) and os.path.getmtime(out_path) >= newest:
        return
    emit(stl_dir, out_path)


try:
    Import("env")  # noqa: F821 - defined when PlatformIO runs this
    run(env.subst("$PROJECT_DIR"))  # noqa: F821
except NameError:
    if __name__ == "__main__":
        run(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
